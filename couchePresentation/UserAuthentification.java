    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String motdePasse = motdePasseUser.getText();
        String nom = nomUser.getText();
        String comboType = (String)  comboTypeUser.getSelectedItem();
        
        //        int response = JOptionPane.showConfirmDialog(null, "Êtes-vous sûr de vouloir quitter ?", "Confirmation", JOptionPane.YES_NO_OPTION);
        GestionUser g = new GestionUser();
        if(g.verifierAccess(nom, motdePasse, comboType)){
            JOptionPane.showMessageDialog(this, "Bienvenue Utilisateur " + nom ,
                "Succès",
                JOptionPane.INFORMATION_MESSAGE);
            if(comboType.equals("docteur")){
                DocteurUI DUI = new DocteurUI(nomUser.getText());
                DUI.setVisible(true);
            }else{
                CrewUI CUI = new CrewUI(motdePasseUser.getText());
                CUI.setVisible(true);
            }
            

            // Close the current window
            this.dispose();

        }else{
            JOptionPane.showMessageDialog(this, "il y a une erreur " ,
                "Erreur",
                JOptionPane.INFORMATION_MESSAGE);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

