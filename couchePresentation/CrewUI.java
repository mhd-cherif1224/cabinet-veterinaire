    private void precedentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_precedentActionPerformed

        try {

            GestionProduit g = new GestionProduit();
            RendezVousDAO rdvDao = new RendezVousDAO();
            AnimalDAO animalDao = new AnimalDAO();
            PropDAO propDao = new PropDAO();

            g.eraseProduitUtiliser();
            
            // 1) Get previous RDV
        RendezVous prevRdv = rdvDao.getPrevious(currentRdvId);

        if (prevRdv == null) {
            JOptionPane.showMessageDialog(this, "Aucun rendez-vous précédent");
            return;
        }

        currentRdvId = prevRdv.getId();

        // 2) Get Animal
        Animal ani = animalDao.getById(prevRdv.getAnimalId());

        // 3) Get Proprietaire
        Prop p = propDao.getById(ani.getProprietaireId());

        // 4) Format tache for HTML
        String tache = prevRdv.getTache();
        tache = tache.replace("\r\n", "<br>").replace("\n", "<br>");

        // 5) Update labels
        idRdvLBL.setText(String.valueOf(prevRdv.getId()));
        dateRdvLBL.setText(String.valueOf(prevRdv.getDate()));
        tacheRdvLBL.setText("<html>" + tache + "</html>");

        idAnimalLBL.setText(String.valueOf(ani.getId()));
        nomAnimalLBL.setText(ani.getNom());
        especeAnimalLBL.setText(ani.getEspece());
        ageAnimalLBL.setText(String.valueOf(ani.getAge()));
        poidsAnimalLBL.setText(String.valueOf(ani.getPoidsKg()));

        idPropLBL.setText(String.valueOf(p.getId()));
        nomPropLBL.setText(p.getNom());
        telePropLBL.setText(p.getTelephone());
        adressePropLBL.setText(p.getAdresse());

        } catch (Exception ex) {
            ex.printStackTrace();
            JOptionPane.showMessageDialog(this, "Erreur : " + ex.getMessage());
        }

    }//GEN-LAST:event_precedentActionPerformed

