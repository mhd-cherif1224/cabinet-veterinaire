    private void deleteSelectedProps() {
    int row = myTable.getSelectedRow();

    GestiondesProprietaire gestionProp = new GestiondesProprietaire();
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Select a row first.");
        return;
    }

    int id = (int) myTable.getValueAt(row, 0);

    int choice = JOptionPane.showConfirmDialog(
            this,
            "Delete this owner?",
            "Confirmer",
            JOptionPane.YES_NO_OPTION
    );

    if (choice == JOptionPane.YES_OPTION) {

        boolean success = gestionProp.deleteProp(id);

        if (success) {
            JOptionPane.showMessageDialog(this, "Proprietaire deleted.");
            loadProps(); // refresh table
        } else {
            JOptionPane.showMessageDialog(this, "Delete failed.");
        }
    }
}

    
    public void loadProps() {
    DefaultTableModel model = (DefaultTableModel) myTable.getModel();
    model.setRowCount(0);
    GestiondesProprietaire gestionProp = new GestiondesProprietaire();
    List<Prop> proprietaires = gestionProp.getAllProps();

    for (Prop p : proprietaires) {
        model.addRow(new Object[]{
            p.getId(),
            p.getNom(),
            p.getTelephone(),
            p.getAdresse()
        });
    }
}


