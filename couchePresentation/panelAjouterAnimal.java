    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try{
            String nom = nomTxt.getText();
            String espece = especeTxt.getText();
            double poids = Double.parseDouble(poidsTxt.getText());
            int age = Integer.parseInt(ageTxt.getText());
            int id = Integer.parseInt(idProp.getText());

            
 

            //        int response = JOptionPane.showConfirmDialog(null, "Êtes-vous sûr de vouloir quitter ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            GestionAnimal g = new GestionAnimal();
            g.addAnimal(nom, espece, age, poids, id);

            JOptionPane.showMessageDialog(this, " ajouté avec succès " + nom + " " + espece + " " + age + "" + poids + "" + id,
                "Succès",
                JOptionPane.INFORMATION_MESSAGE);
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this,
            "⚠️ Erreur : veuillez entrer des valeurs numériques valides .",
            "Erreur de saisie",
            JOptionPane.ERROR_MESSAGE);
            
        }
    }//GEN-LAST:event_jButton2ActionPerformed

