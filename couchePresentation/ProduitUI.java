    private void deleteSelectedProduct() {
    int row = myTable.getSelectedRow();
    
    GestionProduit gestionProduit = new GestionProduit();


    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Select a row first.");
        return;
    }

    int id = (int) myTable.getValueAt(row, 0);

    int choice = JOptionPane.showConfirmDialog(
            this,
            "Delete this product?",
            "Confirm",
            JOptionPane.YES_NO_OPTION
    );

    if (choice == JOptionPane.YES_OPTION) {

        boolean success = gestionProduit.deleteProduct(id);

        if (success) {
            JOptionPane.showMessageDialog(this, "Product deleted.");
            loadTableData(); // refresh
        } else {
            JOptionPane.showMessageDialog(this, "Delete failed.");
        }
    }
}


    
   public void loadProducts() {
    DefaultTableModel model = (DefaultTableModel) myTable.getModel();
    model.setRowCount(0);
    GestionProduit gestionProduit = new GestionProduit();


    List<Produit> products = gestionProduit.getAllProducts();

    for (Produit a : products) {
        model.addRow(new Object[]{
            a.getId(),
            a.getNom(),
            a.getQuantite(),
            a.getPrix()
        });
    }
}

    
