    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try{
        String nom = nomUser.getText();
        String prenom = prenomUser.getText();
        String Address = Adresse.getText();
        String mail = Email.getText();
        int num = Integer.parseInt(telephoneNum.getText());
                
        String sexe = null;

        if (hommeRadio.isSelected()) {
            sexe = "Male";
        } else if (femmeRadio.isSelected()) {
            sexe = "Female";
        
        }
        String motdePasse = motdePasseUser.getText();
        String type = (String) typeCombo.getSelectedItem();
        
        
        GestionUser gu = new GestionUser();
        gu.addUser(nom, prenom, sexe, Address, mail, num, motdePasse, type);
        
        if(type.equals("docteur")){
            GestionDocteur d = new GestionDocteur();
            d.addDocteur(nom, prenom, sexe, Address, mail, num, motdePasse);
        
        
        }if(type.equals("crew")){
            GestionCrew c = new GestionCrew();
            c.addCrew(nom, prenom, sexe, Address, mail, num, motdePasse);
        }

        JOptionPane.showMessageDialog(this, "Utilisateur ajouté avec succès " + nom + " " + motdePasse,
                "Succès",
                JOptionPane.INFORMATION_MESSAGE);
        
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this,
            "⚠️ Erreur : veuillez entrer des valeurs numériques valides .",
            "Erreur de saisie",
            JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

