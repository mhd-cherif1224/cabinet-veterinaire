    private void  deleteSelectedProduct() {
    int row = myTable.getSelectedRow();

    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Select a row first.");
        return;
    }

    // get admin ID from column 0
    int id = (int) myTable.getValueAt(row, 0);

    int choice = JOptionPane.showConfirmDialog(this,
            "Delete this product?",
            "Confirm",
            JOptionPane.YES_NO_OPTION);

    if (choice == JOptionPane.YES_OPTION) {
        
        GestionProduit g = new GestionProduit();
        boolean success = g.deleteProduit(id);

        if (success) {
            JOptionPane.showMessageDialog(this, "produit deleted.");
            loadTableData(); // refresh the table
        } else {
            JOptionPane.showMessageDialog(this, "Delete failed.");
        }
    }
}

    
    public void loadProducts() {
    DefaultTableModel model = (DefaultTableModel) myTable.getModel();
    model.setRowCount(0);
    GestionProduit gestion = new GestionProduit();

    List<Produit> products = gestion.getAllUtiliser();

    for (Produit a : products) {
        model.addRow(new Object[] {
            a.getId(),
            a.getNom(),
            a.getQuantite(),
            a.getPrix()
        });
    }
}

    
