    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try{
            String nom = nomProduit.getText();
            int quant = Integer.parseInt(quantProduit.getText());
            double prix = Double.parseDouble(prixProduit.getText());



            //        int response = JOptionPane.showConfirmDialog(null, "Êtes-vous sûr de vouloir quitter ?", "Confirmation", JOptionPane.YES_NO_OPTION);
            GestionProduit g = new GestionProduit();
            g.addProduit(nom, quant, prix);

            JOptionPane.showMessageDialog(this, "Admin ajouté avec succès " + nom + " " + quant + " " + prix,
                "Succès",
                JOptionPane.INFORMATION_MESSAGE);

        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this,
            "⚠️ Erreur : veuillez entrer des valeurs numériques valides .",
            "Erreur de saisie",
            JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_jButton2ActionPerformed

