    private void loadTableData() {
    DefaultTableModel model = (DefaultTableModel) myTable.getModel();
    model.setRowCount(0);

    GestiondesRendezVous gestionRendez = new GestiondesRendezVous();
    List<RendezVous> rdvs = gestionRendez.getAllRendezVous();

    for (RendezVous r : rdvs) {
        model.addRow(new Object[] {
            r.getId(),
            r.getDate(),
            r.getHeure(),
            r.getAnimalId()
        });
    }
}

    
    private void deleteSelectedRendezVous() {
    int row = myTable.getSelectedRow();
    
    GestiondesRendezVous gestionRendez = new GestiondesRendezVous();
    
    if (row == -1) {
        JOptionPane.showMessageDialog(this, "Select a row first.");
        return;
    }

    int id = (int) myTable.getValueAt(row, 0);

    int choice = JOptionPane.showConfirmDialog(this,
            "Delete this rendez-vous ?",
            "Confirmer",
            JOptionPane.YES_NO_OPTION);

    if (choice == JOptionPane.YES_OPTION) {

        boolean success = gestionRendez.deleteRendezVous(id);

        if (success) {
            JOptionPane.showMessageDialog(this, "Rendez-vous deleted.");
            loadTableData();
        } else {
            JOptionPane.showMessageDialog(this, "Delete failed.");
        }
    }
}

