    private void label1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_label1MouseClicked
        String tabName = "Ajouter un Admin";

    // check if tab already exists
    for (int i = 0; i < mainPanel.getTabCount(); i++) {
        if (mainPanel.getTitleAt(i).equals(tabName)) {
            mainPanel.setSelectedIndex(i); // switch to existing tab
            sidebarPanel.setVisible(false);
            adminInterfaceLabel.setText("Admin Interface");
            return; // stop — do NOT create another one
        }
    }

    // create it once
    panelAjouterAdmin ajouterAdmi = new panelAjouterAdmin();
    mainPanel.addTab(tabName, ajouterAdmi);
    mainPanel.setSelectedIndex(mainPanel.getTabCount() - 1);

    sidebarPanel.setVisible(false);
    adminInterfaceLabel.setText("Admin Interface");
    }//GEN-LAST:event_label1MouseClicked

    
